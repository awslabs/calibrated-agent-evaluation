"""Contract tests binding the fixture oracles to the shipped code.

The ``fixtures/expected/run/`` oracles are the frozen outputs the shipped ``run/`` code produces
over a documented scenario (they were generated by that code, not hand-authored). These tests re-run
the shipped functions on each oracle's recorded inputs and assert the outputs still match -- so a
drift in the run maths breaks the build, and the acceptance harness compares against a live oracle.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from _helpers import TEST_STAMP, rate_ids_by_mode
from calibrated_agent_evaluation.calibrate.record import Bound, CalibrationRecord
from calibrated_agent_evaluation.run.drift_report import DriftThresholds, input_drift
from calibrated_agent_evaluation.run.gate import CiGateRequest, run_ci_gate
from calibrated_agent_evaluation.run.report import ModeCounts, ModeKey
from calibrated_agent_evaluation.run.trend import trend_report
from calibrated_agent_evaluation.schema.types import Label

_ORACLES = Path(__file__).resolve().parent.parent / "fixtures" / "expected" / "run"


def _load(name: str) -> dict:
    return json.loads((_ORACLES / name).read_text(encoding="utf-8"))


def test_trend_oracle_matches_shipped_trend_report() -> None:
    """Shipped trend_report reproduces fixtures/expected/run/trend_orderbot.json."""
    oracle = _load("trend_orderbot.json")
    over = ModeKey(failure_type="trusted_broken_policy_tool")
    dropped = ModeKey(failure_type="dropped_material_fact", agent="intake")
    strong = CalibrationRecord(
        provenance=TEST_STAMP,
        calib_id="calib-orderbot-refund",
        judge_id="orderbot-refund",
        model="bedrock/claude-sonnet-4-6",
        prompt_version="demo-v1",
        hunted_set_id="hunted-ob",
        n_pos=80,
        n_neg=80,
        tpr=Bound(point=0.95, lb95=0.90, n=80),
        tnr=Bound(point=0.95, lb95=0.90, n=80),
        youden_j=0.90,
        result="CERTIFIED",
    )
    weak = CalibrationRecord(
        provenance=TEST_STAMP,
        calib_id="calib-intake-dropped",
        judge_id="intake-dropped",
        model="bedrock/claude-sonnet-4-6",
        prompt_version="demo-v1",
        hunted_set_id="hunted-intake",
        n_pos=80,
        n_neg=80,
        tpr=Bound(point=0.70, lb95=0.65, n=80),
        tnr=Bound(point=0.70, lb95=0.65, n=80),
        youden_j=0.40,
        result="CERTIFIED",
    )
    counts = {
        over: ModeCounts(
            mode=over, n_total=200, n_judged_fail=32, calib_id="calib-orderbot-refund"
        ),
        dropped: ModeCounts(
            mode=dropped, n_total=160, n_judged_fail=80, calib_id="calib-intake-dropped"
        ),
    }
    rate = {over: [1] * 32 + [0] * 168, dropped: [1] * 80 + [0] * 80}

    points = trend_report(
        counts,
        {over: strong, dropped: weak},
        rate,
        seed=oracle["seed"],
        rate_trace_ids=rate_ids_by_mode(rate),
    )
    got = {
        (p.mode.failure_type, p.mode.agent): (
            p.corrected_rate.point,
            p.corrected_rate.refusal_reason,
        )
        for p in points
    }
    raw_by_key = {(p.mode.failure_type, p.mode.agent): p.raw_rate for p in points}
    for exp in oracle["expected_points"]:
        key = (exp["mode"]["failure_type"], exp["mode"]["agent"])
        assert key in got
        point, reason = got[key]
        assert point == exp["corrected_rate"]["point"]
        assert reason == exp["corrected_rate"]["refusal_reason"]
        raw, want = raw_by_key[key], exp["raw_rate"]
        assert raw.point == want["point"]
        assert round(raw.lo, 6) == want["lo"]
        assert round(raw.hi, 6) == want["hi"]
        assert (raw.method, raw.level, raw.sided, raw.n) == (
            want["method"],
            want["level"],
            want["sided"],
            want["n"],
        )


def test_input_drift_oracle_matches_shipped_input_drift() -> None:
    """Shipped input_drift reproduces fixtures/expected/run/input_drift.json (± 1e-6)."""
    oracle = _load("input_drift.json")
    report = input_drift(
        oracle["inputs"]["baseline"],
        oracle["inputs"]["fresh"],
        dimension=oracle["dimension"],
        thresholds=DriftThresholds(**oracle["inputs"]["thresholds"]),
        bins=oracle["inputs"]["bins"],
        n_permutations=oracle["inputs"]["n_permutations"],
        seed=oracle["inputs"]["seed"],
    )
    got = {m.name: m for m in report.metrics}
    for exp in oracle["expected_metrics"]:
        metric = got[exp["name"]]
        assert metric.value == pytest.approx(exp["value"], abs=1e-6)
        assert metric.p_value == pytest.approx(exp["p_value"], abs=1e-6)
        assert (metric.method, metric.threshold, metric.exceeded) == (
            exp["method"],
            exp["threshold"],
            exp["exceeded"],
        )


def test_gate_oracle_matches_shipped_run_ci_gate() -> None:
    """Shipped run_ci_gate reproduces fixtures/expected/run/gate_decision.json."""
    oracle = _load("gate_decision.json")
    over = ModeKey(failure_type="trusted_broken_policy_tool")
    dropped = ModeKey(failure_type="dropped_material_fact", agent="intake")

    def _lbl(tid: str, outcome: str) -> Label:
        return Label(trace_id=tid, span_id=None, kind="llm-judge", outcome=outcome, critique="c")  # type: ignore[arg-type]

    la = [_lbl(f"OR{i}", "PASS") for i in range(48)] + [
        _lbl(f"OR{i}", "FAIL") for i in range(48, 50)
    ]
    lb = [_lbl(f"DR{i}", "PASS") for i in range(10)] + [
        _lbl(f"DR{i}", "FAIL") for i in range(10, 20)
    ]
    gold: dict[tuple[str, str | None], ModeKey] = {
        **{(x.trace_id, None): over for x in la},
        **{(x.trace_id, None): dropped for x in lb},
    }
    dec = run_ci_gate(CiGateRequest(labels=la + lb, gold=gold, threshold=oracle["threshold"]))

    assert dec.passed == oracle["expected"]["passed"]
    assert [m.failure_type for m in dec.failing_modes] == [
        m["failure_type"] for m in oracle["expected"]["failing_modes"]
    ]
    assert dec.n_modes == oracle["expected"]["n_modes"]
