"""Contract tests binding the fixture oracles to the shipped code.

The ``fixtures/expected/improve/`` oracles are the frozen outputs the shipped ``improve/`` code
produces over a documented scenario (they were generated by that code, not hand-authored). These
tests re-run the shipped functions on each oracle's recorded inputs and assert the outputs still
match -- so a drift in the improve maths breaks the build, and the acceptance harness compares
against a live oracle.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from _helpers import TEST_INTERVAL_KIND
from calibrated_agent_evaluation.attribution import CrewDefinition, CrewOutcomes
from calibrated_agent_evaluation.attribution.types import ExpectedProcess
from calibrated_agent_evaluation.calibrate.record import Interval
from calibrated_agent_evaluation.improve import (
    GuardSlice,
    PairedObs,
    crew_panel,
    guard_panel,
    paired_mcnemar,
)

_ORACLES = Path(__file__).resolve().parent.parent / "fixtures" / "expected" / "improve"


def _load(name: str) -> dict:
    return json.loads((_ORACLES / name).read_text(encoding="utf-8"))


def _iv(point: float) -> Interval:
    return Interval(
        point=point, lo=point - 0.05, hi=point + 0.05, refusal_reason=None, **TEST_INTERVAL_KIND
    )


def _pairs(before_fail: int, after_fail: int, n: int) -> list[PairedObs]:
    return [
        PairedObs(f"ORD-{i}", before_fail=(i < before_fail), after_fail=(i < after_fail))
        for i in range(n)
    ]


def test_paired_oracle_matches_shipped_mcnemar() -> None:
    """Shipped paired_mcnemar reproduces the paired_orderbot.json oracle."""
    oracle = _load("paired_orderbot.json")
    small_in = oracle["small"]["inputs"]
    small = paired_mcnemar(_pairs(small_in["before_fail"], small_in["after_fail"], small_in["n"]))
    assert small.method == oracle["small"]["expected"]["method"]
    # The p-value is a sum of binomial terms; libm differs in the last bits across platforms.
    assert small.p_value == pytest.approx(oracle["small"]["expected"]["p_value"], abs=1e-12)
    effect = oracle["small"]["expected"]["effect"]
    assert small.effect.point == effect["point"]
    assert small.effect.lo == pytest.approx(effect["lo"], abs=1e-12)
    assert small.effect.hi == pytest.approx(effect["hi"], abs=1e-12)

    zero_in = oracle["zero"]["inputs"]
    zero = paired_mcnemar(_pairs(zero_in["before_fail"], zero_in["after_fail"], zero_in["n"]))
    assert zero.method == "undefined"
    assert zero.p_value is None


def test_guard_panel_oracle_matches_shipped_panel() -> None:
    """Shipped guard_panel reproduces fixtures/expected/improve/guard_panel.json."""
    oracle = _load("guard_panel.json")
    regression_p = oracle["inputs"]["regression_p"]
    slices = [
        GuardSlice(
            name=name, kind="other", regression_p=p, rate_before=_iv(0.1), rate_after=_iv(0.1)
        )
        for name, p in regression_p.items()
    ]
    panel = guard_panel(slices, alpha=oracle["inputs"]["alpha"])
    assert panel.method == oracle["expected"]["method"]
    assert panel.m == oracle["expected"]["m"]
    assert sorted(panel.regressed) == sorted(oracle["expected"]["regressed"])


def _crew() -> CrewDefinition:
    return CrewDefinition(
        agents=("intake", "policy-checker"),
        handoffs=("intake->policy-checker",),
        scenarios={
            "s1": ExpectedProcess(
                scenario="s1",
                expected_agents=("intake", "policy-checker"),
                terminal_decision="approve",
                payout_allowed=True,
                escalation_required=False,
            )
        },
        rules=(),
    )


def test_relocation_oracle_matches_shipped_crew_panel() -> None:
    """Shipped crew_panel reproduces the relocation_claimscrew.json verdicts."""
    oracle = _load("relocation_claimscrew.json")
    crew = _crew()
    for key in ("relocation", "improved"):
        case = oracle[key]
        before = CrewOutcomes(**case["inputs"]["before"])
        after = CrewOutcomes(**case["inputs"]["after"])
        panel = crew_panel(
            crew,
            before,
            after,
            touched_agent=case["inputs"]["touched_agent"],
            slices=[
                GuardSlice(
                    name="policy-checker",
                    kind="agent",
                    regression_p=0.8,
                    rate_before=_iv(0.1),
                    rate_after=_iv(0.1),
                )
            ],
        )
        assert panel.relocation is not None
        assert panel.relocation.verdict == case["expected"]["verdict"]
        assert panel.relocation.relocated_from == case["expected"]["relocated_from"]
